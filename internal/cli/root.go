// Package cli implements the muninn command line.
package cli

import (
	"errors"
	"fmt"
	"os"

	"github.com/spf13/cobra"

	"github.com/lamngockhuong/muninn/internal/content"
	"github.com/lamngockhuong/muninn/internal/review"
)

const defaultDir = "muninn"

// exitError carries a specific process exit code without printing usage.
type exitError struct {
	code int
	msg  string
}

func (e *exitError) Error() string { return e.msg }

// Execute runs the CLI and returns the process exit code.
func Execute(version string) int {
	root := NewRoot(version)
	if err := root.Execute(); err != nil {
		var ee *exitError
		if errors.As(err, &ee) {
			if ee.msg != "" {
				fmt.Fprintln(os.Stderr, ee.msg)
			}
			return ee.code
		}
		fmt.Fprintln(os.Stderr, "error:", err)
		return 2
	}
	return 0
}

// NewRoot builds the command tree.
func NewRoot(version string) *cobra.Command {
	root := &cobra.Command{
		Use:           "muninn",
		Short:         "Product atlas generated by AI, reviewed by people, served from one binary",
		SilenceUsage:  true,
		SilenceErrors: true,
	}
	root.AddCommand(
		newInitCmd(),
		newSchemaCmd(),
		newValidateCmd(),
		newStatusCmd(),
		newReviewCmd(),
		newVersionCmd(version),
	)
	for _, extra := range extraCommands {
		root.AddCommand(extra(version))
	}
	return root
}

// extraCommands lets other files (serve, capture, export) register commands.
var extraCommands []func(version string) *cobra.Command

func newVersionCmd(version string) *cobra.Command {
	return &cobra.Command{
		Use:   "version",
		Short: "Print the muninn version",
		Args:  cobra.NoArgs,
		Run: func(cmd *cobra.Command, _ []string) {
			fmt.Fprintln(cmd.OutOrStdout(), "muninn", version)
		},
	}
}

// loaded is a content index with computed review states.
type loaded struct {
	ix       *content.Index
	hasher   *review.Hasher
	statuses map[string]review.Status
}

func load(dir string) (*loaded, error) {
	ix, err := content.Load(dir)
	if err != nil {
		return nil, err
	}
	h := review.NewHasher(ix.RepoRoot)
	return &loaded{ix: ix, hasher: h, statuses: review.ComputeAll(ix, h)}, nil
}

func addDirFlag(cmd *cobra.Command, dir *string) {
	cmd.Flags().StringVar(dir, "dir", defaultDir, "content directory containing muninn.yaml")
}

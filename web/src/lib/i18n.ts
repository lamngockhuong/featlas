const dicts: Record<UiLang, Dict> = { en, vi, ja }

export type Translate = (key: MsgKey, vars?: Record<string, string | number>) => string

export function translator(lang: UiLang): Translate {
  const dict = dicts[lang] ?? en
  return (key, vars) => {
    let s = dict[key] ?? en[key] ?? key
    if (vars) {
      for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
    }
    return s
  }
}

export function detectUiLang(): UiLang {
  const nav = typeof navigator !== 'undefined' ? navigator.language.slice(0, 2) : 'en'
  return (UI_LANGS as string[]).includes(nav) ? (nav as UiLang) : 'en'
}
